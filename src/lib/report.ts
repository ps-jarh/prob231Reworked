import type { TestRecord, AuditEvent } from './types';
import { shortHash } from './services/evidenceService';

export function exportPdfReport(t: TestRecord, events: AuditEvent[]) {
  const rows = events.filter((e) => e.testId === t.testId).sort((a, b) => a.timestamp.localeCompare(b.timestamp));
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>BiOrion Evidence Report ${t.testId}</title>
<style>
  body{font-family:Helvetica,Arial,sans-serif;color:#111827;margin:40px;font-size:12px}
  h1{font-size:20px;margin:0} h2{font-size:13px;text-transform:uppercase;letter-spacing:.08em;color:#0e7490;border-bottom:1px solid #e5e7eb;padding-bottom:4px;margin-top:26px}
  .brand{display:flex;justify-content:space-between;align-items:center;border-bottom:3px solid #164e63;padding-bottom:14px}
  .badge{display:inline-block;padding:3px 10px;border-radius:4px;font-weight:700;text-transform:uppercase;font-size:11px}
  table{width:100%;border-collapse:collapse;margin-top:8px} td,th{padding:6px 8px;border:1px solid #e5e7eb;text-align:left;font-size:11px}
  th{background:#f3f4f6;text-transform:uppercase;font-size:10px;letter-spacing:.05em;color:#6b7280}
  .mono{font-family:'Courier New',monospace;font-size:10px;word-break:break-all}
  .grid td{border:none;padding:3px 16px 3px 0}
  .lbl{color:#6b7280;font-size:10px;text-transform:uppercase}
  .foot{margin-top:30px;font-size:10px;color:#6b7280;border-top:1px solid #e5e7eb;padding-top:10px}
  img{max-width:280px;border:1px solid #d1d5db}
  .warn{background:#fffbeb;border:1px solid #fbbf24;padding:8px 10px;font-size:10px;margin-top:16px}
</style></head><body>
<div class="brand">
  <div><h1>BiOrion</h1><div style="color:#6b7280">Field Drug Testing &amp; Evidence Management — Evidence Report</div></div>
  <div style="text-align:right"><div class="mono" style="font-size:14px;font-weight:700">${t.testId}</div>
  <div class="badge" style="background:${t.result === 'positive' ? '#fee2e2;color:#b91c1c' : t.result === 'negative' ? '#d1fae5;color:#047857' : '#fef3c7;color:#b45309'}">${t.result}</div></div>
</div>
<h2>Test Details</h2>
<table class="grid"><tr><td class="lbl">Officer</td><td class="lbl">Test Type</td><td class="lbl">Date &amp; Time</td></tr>
<tr><td>${t.officerName} (${t.officerId})</td><td>${t.testType}</td><td>${new Date(t.timestamp).toLocaleString()}</td></tr>
<tr><td class="lbl">Location</td><td class="lbl">Coordinates</td><td class="lbl">Device ID</td></tr>
<tr><td>${t.location}</td><td>${t.latitude.toFixed(5)}, ${t.longitude.toFixed(5)}</td><td class="mono">${t.deviceId}</td></tr>
<tr><td class="lbl">AI Confidence</td><td class="lbl">Calibration Confidence</td><td class="lbl">Evidence Status</td></tr>
<tr><td>${t.confidence.toFixed(1)}%</td><td>${t.calibrationConfidence.toFixed(1)}%</td><td>${t.status === 'verified' ? 'Verified' : 'Pending Review'}</td></tr></table>
<h2>Captured Evidence</h2>
<table><tr><th>Original Capture</th><th>Calibrated Image</th></tr>
<tr><td><img src="${t.imageUrl}"></td><td><img src="${t.calibratedImageUrl}"></td></tr></table>
<h2>Integrity</h2>
<p><b>SHA-256 Evidence Hash</b></p><p class="mono">${t.evidenceHash}</p>
<p>Cryptographic timestamp recorded · Audit record created · Image ID <span class="mono">${t.imageId}</span></p>
<h2>Audit Trail</h2>
<table><tr><th>Timestamp</th><th>Event ID</th><th>Actor</th><th>Action</th></tr>
${rows.map((e) => `<tr><td class="mono">${new Date(e.timestamp).toLocaleString()}</td><td class="mono">${e.eventId}</td><td>${e.actor}</td><td>${e.action}</td></tr>`).join('')}
</table>
<div class="warn"><b>Notice:</b> This report documents a field screening assessment produced by the BiOrion decision-support prototype. It is not legally conclusive forensic identification and must be verified according to applicable laboratory forensic procedures.</div>
<div class="foot">Generated by BiOrion · Evidence integrity reference ${shortHash(t.evidenceHash)} · Report generated ${new Date().toLocaleString()}</div>
<script>window.onload=()=>setTimeout(()=>window.print(),400)</script>
</body></html>`;
  const w = window.open('', '_blank');
  if (!w) return;
  w.document.write(html);
  w.document.close();
}
